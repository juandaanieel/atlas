from __future__ import annotations

import json
import os
import shutil
import uuid
from pathlib import Path

from atlas.analyzer.discovery import resolve_analysis_root
from atlas.analyzer.payload import analyze_path
from atlas.analyzer.snapshot import AnalysisSnapshot
from atlas.output import checked_output_path, ensure_child_directory
from atlas.vault import write_vault


ATLAS_MARKER = ".atlas-owned"
GENERATED_MARKER = ".atlas-generated"
STAGING_MARKER = ".atlas-dashboard-staging"


def refresh_project(
    root: str | Path,
    *,
    job_id: str | None = None,
) -> dict:
    """Regenerate Atlas-owned output without replacing a usable failed build."""
    root_path = resolve_analysis_root(root)
    if Path(root).expanduser().is_symlink():
        raise ValueError(f"Project directory cannot be a symlink: {root}")

    snapshot = analyze_path(root_path)
    atlas_dir = _atlas_directory(root_path)
    staging_parent = ensure_child_directory(atlas_dir, ".staging")
    staging_dir = checked_output_path(staging_parent, job_id or str(uuid.uuid4()))
    staging_dir.mkdir()
    (staging_dir / STAGING_MARKER).write_text("Atlas dashboard staging\n", encoding="utf-8")

    try:
        payload_path = staging_dir / "atlas.json"
        payload_path.write_text(snapshot.to_json(indent=2) + "\n", encoding="utf-8")
        AnalysisSnapshot.from_json(payload_path.read_text(encoding="utf-8"))

        staged_vault = staging_dir / "vault"
        write_vault(root_path, snapshot, out=staged_vault)
        staged_generated = staged_vault / "00-atlas"
        (staged_generated / GENERATED_MARKER).write_text(
            "Generated by Atlas. Safe to replace as one unit.\n",
            encoding="utf-8",
        )

        _install_outputs(atlas_dir, payload_path, staged_generated)
        return {
            "snapshot_id": snapshot["snapshot_id"],
            "atlas_version": snapshot["atlas_version"],
            "generated_at": snapshot["generated_at"],
        }
    finally:
        _remove_staging_directory(staging_parent, staging_dir)


def _atlas_directory(root: Path) -> Path:
    atlas_dir = checked_output_path(root, ".atlas")
    atlas_dir.mkdir(exist_ok=True)
    if not atlas_dir.is_dir():
        raise NotADirectoryError(f"Atlas output is not a directory: {atlas_dir}")
    marker = checked_output_path(atlas_dir, ATLAS_MARKER)
    if not marker.exists():
        marker.write_text(
            "Atlas owns generated files in this directory, not project source.\n",
            encoding="utf-8",
        )
    _recover_interrupted_vault_swap(atlas_dir)
    return atlas_dir


def _install_outputs(
    atlas_dir: Path,
    staged_payload: Path,
    staged_generated: Path,
) -> None:
    payload_path = checked_output_path(atlas_dir, "atlas.json")
    previous_payload = checked_output_path(atlas_dir, "atlas.previous.json")
    vault_dir = ensure_child_directory(atlas_dir, "vault")
    generated_dir = checked_output_path(vault_dir, "00-atlas")
    previous_generated = checked_output_path(vault_dir, "00-atlas.previous")

    if payload_path.exists():
        if not payload_path.is_file():
            raise ValueError(f"Atlas snapshot is not a file: {payload_path}")
        backup_payload = staged_payload.parent / "atlas.previous.json"
        shutil.copy2(payload_path, backup_payload)
        os.replace(backup_payload, previous_payload)

    _install_generated_directory(
        generated_dir,
        previous_generated,
        staged_generated,
    )
    try:
        os.replace(staged_payload, payload_path)
    except BaseException:
        _restore_generated_directory(generated_dir, previous_generated)
        raise


def _install_generated_directory(
    generated_dir: Path,
    previous_generated: Path,
    staged_generated: Path,
) -> None:
    if previous_generated.exists():
        _remove_generated_directory(previous_generated)

    had_previous = generated_dir.exists()
    if had_previous:
        _verify_generated_directory(generated_dir)
        os.replace(generated_dir, previous_generated)

    try:
        os.replace(staged_generated, generated_dir)
    except BaseException:
        if had_previous and previous_generated.exists():
            os.replace(previous_generated, generated_dir)
        raise


def _restore_generated_directory(
    generated_dir: Path,
    previous_generated: Path,
) -> None:
    if generated_dir.exists():
        _remove_generated_directory(generated_dir)
    if previous_generated.exists():
        os.replace(previous_generated, generated_dir)


def _verify_generated_directory(path: Path) -> None:
    if path.is_symlink() or not path.is_dir():
        raise ValueError(f"Refusing to replace unsafe generated vault: {path}")
    marker = path / GENERATED_MARKER
    manifest = path / "manifest.json"
    if marker.is_file():
        return
    if not manifest.is_file() or manifest.is_symlink():
        raise ValueError(f"Refusing to replace unowned vault directory: {path}")
    try:
        document = json.loads(manifest.read_text(encoding="utf-8"))
    except json.JSONDecodeError as error:
        raise ValueError(f"Refusing to replace invalid vault directory: {path}") from error
    if not isinstance(document, dict) or "atlas_version" not in document:
        raise ValueError(f"Refusing to replace unowned vault directory: {path}")


def _remove_generated_directory(path: Path) -> None:
    _verify_generated_directory(path)
    shutil.rmtree(path)


def _remove_staging_directory(staging_parent: Path, staging_dir: Path) -> None:
    if not staging_dir.exists():
        return
    if staging_dir.is_symlink():
        raise ValueError(f"Refusing to remove symlinked staging directory: {staging_dir}")
    if staging_dir.parent.resolve() != staging_parent.resolve():
        raise ValueError(f"Refusing to remove staging directory outside Atlas: {staging_dir}")
    if not (staging_dir / STAGING_MARKER).is_file():
        raise ValueError(f"Refusing to remove unowned staging directory: {staging_dir}")
    shutil.rmtree(staging_dir)


def _recover_interrupted_vault_swap(atlas_dir: Path) -> None:
    vault_dir = checked_output_path(atlas_dir, "vault")
    if not vault_dir.exists():
        return
    if not vault_dir.is_dir():
        raise NotADirectoryError(f"Atlas vault is not a directory: {vault_dir}")

    generated = checked_output_path(vault_dir, "00-atlas")
    previous = checked_output_path(vault_dir, "00-atlas.previous")
    if not generated.exists() and previous.exists():
        _verify_generated_directory(previous)
        os.replace(previous, generated)
        return
    if not generated.exists() or not previous.exists():
        return

    payload = checked_output_path(atlas_dir, "atlas.json")
    payload_snapshot = _snapshot_id(payload)
    generated_snapshot = _vault_snapshot_id(generated)
    previous_snapshot = _vault_snapshot_id(previous)
    if (
        payload_snapshot
        and generated_snapshot != payload_snapshot
        and previous_snapshot == payload_snapshot
    ):
        _remove_generated_directory(generated)
        os.replace(previous, generated)


def _snapshot_id(path: Path) -> str | None:
    if not path.exists():
        return None
    if path.is_symlink() or not path.is_file():
        raise ValueError(f"Refusing to read unsafe Atlas snapshot: {path}")
    try:
        document = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return None
    return document.get("snapshot_id") if isinstance(document, dict) else None


def _vault_snapshot_id(path: Path) -> str | None:
    _verify_generated_directory(path)
    try:
        document = json.loads((path / "manifest.json").read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return None
    return document.get("snapshot_id") if isinstance(document, dict) else None
